"""Set up the KR883 Activity Logger extension on THIS computer.

    python install_extension.py --server https://YOUR-DOMAIN.ngrok.app/tracker --key <KEY> --computer WORKER-PC-1
    python install_extension.py --server local --computer ADMIN-PC           (the tracker PC itself)

Writes extension/kr883-activity-logger/config.js (gitignored), then prints the three Chrome clicks that
cannot be automated. --key defaults to the key in this folder's config.json (only exists on the tracker PC).
"""
import argparse, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXT = os.path.join(HERE, "extension", "kr883-activity-logger")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--server", required=True, help="tracker address, e.g. https://x.ngrok.app/tracker, or 'local'")
    ap.add_argument("--key", help="shared key (from the tracker PC's config.json)")
    ap.add_argument("--computer", required=True, help="name for this computer, shown on the dashboard")
    a = ap.parse_args()

    key = a.key
    if not key:
        try:
            key = json.load(open(os.path.join(HERE, "config.json"), encoding="utf-8"))["key"]
        except Exception:
            sys.exit("No --key given and no config.json here. Ask the owner for the key.")
    server = a.server.strip().rstrip("/")
    url = "http://127.0.0.1:8780/activity" if server == "local" else server + "/activity"
    if not re.match(r"^https?://", url):
        sys.exit("--server must start with https:// (or be 'local')")
    if not re.fullmatch(r"[A-Za-z0-9 ._-]{1,40}", a.computer):
        sys.exit("--computer: letters, digits, space . _ - only (max 40)")

    with open(os.path.join(EXT, "config.js"), "w", encoding="utf-8") as f:
        f.write('// Generated by install_extension.py - do not commit.\n'
                f'self.ACTIVITY_URL = {json.dumps(url)};\nself.ACTIVITY_KEY = {json.dumps(key)};\nself.COMPUTER = {json.dumps(a.computer)};\n')

    # The extension may only talk to hosts listed in its manifest; add this server if it is not an ngrok one.
    mp = os.path.join(EXT, "manifest.json")
    m = json.load(open(mp, encoding="utf-8"))
    origin = re.match(r"^(https?://[^/]+)", url).group(1) + "/*"
    if not any(origin == h or (h.startswith("https://*.") and origin.endswith(h[len("https://*"):])) for h in m["host_permissions"]):
        m["host_permissions"].append(origin)
        json.dump(m, open(mp, "w", encoding="utf-8"), indent=2)
        print("Added", origin, "to the extension's allowed hosts.")

    print(f"\nWrote {os.path.join(EXT, 'config.js')}\n  sending to: {url}\n  computer:   {a.computer}\n")
    print("Now, once, in Chrome (the profile the worker uses for KR883):")
    print("  1. open  chrome://extensions  and switch on 'Developer mode' (top right)")
    print("  2. click 'Load unpacked' and choose:\n       " + EXT)
    print("  3. reload the KR883 tab")
    print("If the extension was already installed, click its reload arrow instead of step 2.")


if __name__ == "__main__":
    main()
